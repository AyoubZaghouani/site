function t(key) {
  return (i18n[state.lang] && i18n[state.lang][key]) || i18n.en[key] || key;
}
function loc(p) {
  return p.i18n
    ? p.i18n[state.lang] || p.i18n.en
    : { title: p.title || "", desc: p.description || "" };
}
function catName(cat) {
  return t("cat_" + cat);
}
function normalizeProductId(id) {
  return String(id);
}

/* ── Language switching (the fix!) ── */
function applyLanguage(lang) {
  state.lang = lang;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const k = el.dataset.i18n;
    if (t(k) !== k) el.textContent = t(k);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document
    .querySelectorAll(".lang-btn")
    .forEach((b) => b.classList.toggle("active", b.dataset.lang === lang));
  renderGrid();
  renderCartDrawer();
}

/* ── Rendering ── */
function getFilteredProducts() {
  return products
    .filter(
      (p) =>
        (state.activeCategory === "all" ||
          p.category === state.activeCategory) &&
        (loc(p).title.toLowerCase().includes(state.searchQuery.toLowerCase()) ||
          catName(p.category)
            .toLowerCase()
            .includes(state.searchQuery.toLowerCase()) ||
          loc(p).desc.toLowerCase().includes(state.searchQuery.toLowerCase())),
    )
    .sort((a, b) => {
      if (state.sortBy === "price-low") return a.price - b.price;
      if (state.sortBy === "price-high") return b.price - a.price;
      if (state.sortBy === "newest")
        return new Date(b.created_at || 0) - new Date(a.created_at || 0);
      return 0;
    });
}

/* ── Load catalog from Supabase ── */
async function loadProducts() {
  productGrid.innerHTML = `<div class="loading-row"><i class="fa-solid fa-spinner fa-spin"></i> <span>${t("loading_products")}</span></div>`;

  await initStorefrontSupabase();
  if (!sb) {
    products = fallbackProducts;
    renderGrid();
    return;
  }

  const { data, error } = await sb
    .from("articles")
    .select("*")
    .order("created_at", { ascending: false });
  if (error) {
    products = fallbackProducts;
    showToast(
      t("load_error") + (error.message ? " (" + error.message + ")" : ""),
    );
    renderGrid();
    return;
  }
  products = (data || []).map((a) => ({
    id: normalizeProductId(a.id),
    category: a.category || "all",
    price: Number(a.price) || 0,
    oldPrice: null,
    isSale: false,
    image: a.image_url || "",
    title: a.title || "",
    description: a.description || "",
    stock: a.stock,
    created_at: a.created_at,
  }));
  if (products.length === 0) {
    products = fallbackProducts;
  }
  renderGrid();
}

function renderGrid() {
  const items = getFilteredProducts();
  resultsCount.textContent =
    items.length === 1
      ? t("showing_one")
      : t("showing").replace("{n}", items.length);
  if (items.length === 0) {
    productGrid.innerHTML = "";
    emptyState.classList.remove("hidden");
    return;
  }
  emptyState.classList.add("hidden");
  productGrid.innerHTML = items
    .map((p) => {
      const productId = normalizeProductId(p.id);
      const wished = state.wishlist.has(productId);
      return `<article class="product-card" data-id="${productId}">
      <div class="card-image-wrapper" onclick="openQuickView('${productId}', event)">
        ${p.isSale ? `<span class="badge-sale">${t("sale")}</span>` : ""}
        <button class="wishlist-card-btn ${wished ? "active" : ""}" aria-label="Wishlist" onclick="toggleWishlist('${productId}', event)">
          <i class="${wished ? "fa-solid" : "fa-regular"} fa-heart"></i>
        </button>
        <img src="${p.image}" alt="${loc(p).title}" loading="lazy" onerror="this.onerror=null;this.src='data:image/gif;base64,R0lGODlhAQABAAAAACH5BAEKAAEALAAAAAABAAEAAAICTAEAOw==';">
        <div class="quick-add-overlay">
          <button class="btn btn-primary btn-sm flex-1" onclick="openQuickView('${productId}', event)"><i class="fa-solid fa-eye"></i> ${t("quick_view")}</button>
          <button class="btn btn-rose btn-sm" onclick="quickAddToCart('${productId}', event)" title="Quick Add"><i class="fa-solid fa-plus"></i></button>
        </div>
      </div>
      <div class="card-details" onclick="openQuickView('${productId}', event)">
        <span class="card-category">${catName(p.category)}</span>
        <h3 class="card-title">${loc(p).title}</h3>
        <div class="card-price-row"><span class="card-price">$${p.price}</span>${p.oldPrice ? `<span class="card-old-price">$${p.oldPrice}</span>` : ""}</div>
      </div>
    </article>`;
    })
    .join("");
}

/* ── Wishlist / Cart ── */
window.toggleWishlist = function (id, e) {
  if (e) e.stopPropagation();
  const normalizedId = normalizeProductId(id);
  if (state.wishlist.has(normalizedId)) {
    state.wishlist.delete(normalizedId);
    showToast(t("toast_wish_remove"));
  } else {
    state.wishlist.add(normalizedId);
    showToast(t("toast_wish_add"));
  }
  updateHeaderBadges();
  renderGrid();
};
window.quickAddToCart = function (id, e) {
  if (e) e.stopPropagation();
  const normalizedId = normalizeProductId(id);
  const ex = state.cart.find((i) => i.id === normalizedId);
  if (ex) ex.qty += 1;
  else state.cart.push({ id: normalizedId, qty: 1, finish: "sage" });
  updateHeaderBadges();
  renderCartDrawer();
  showToast(t("toast_added"));
};
function updateHeaderBadges() {
  if (wishlistCount) wishlistCount.textContent = state.wishlist.size;
  if (cartCount) {
    const q = state.cart.reduce((s, i) => s + i.qty, 0);
    cartCount.textContent = q < 10 ? `0${q}` : q;
  }
}

/* ── Quick View ── */
function getProductTitle(product) {
  if (!product) return "";
  const localizedTitle = loc(product).title;
  if (localizedTitle && localizedTitle.trim()) return localizedTitle.trim();
  return String(product.title || product.name || "").trim();
}

window.openQuickView = function (id, e) {
  if (e) e.stopPropagation();
  const normalizedId = normalizeProductId(id);
  const p = products.find((x) => normalizeProductId(x.id) === normalizedId);
  if (!p) return;
  state.selectedModalProduct = p;
  $("modal-img").src = p.image;
  $("modal-category").textContent = catName(p.category);
  $("modal-title").textContent = getProductTitle(p);
  $("modal-price").textContent = `$${p.price}`;
  $("modal-desc").textContent = loc(p).desc;
  $("modal-qty-val").textContent = modalQty = 1;
  $("modal-badge").classList.toggle("hidden", !p.isSale);
  quickViewModal.classList.remove("hidden");
};
function closeQuickView() {
  quickViewModal.classList.add("hidden");
}

